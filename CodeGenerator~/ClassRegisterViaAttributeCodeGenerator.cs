using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Damdor.Sequentio.CodeGenerator;

/// <summary>
/// Provides source generation helpers for registering classes marked with selected attributes.
/// </summary>
public abstract class ClassRegisterViaAttributeCodeGenerator : ISourceGenerator
{
    /// <summary>
    /// The attribute names recognized by this generator.
    /// </summary>
    public abstract string[] Attributes { get; } 
    
    /// <summary>
    /// Registers the syntax receiver used to discover attributed classes.
    /// </summary>
    /// <param name="context">The Roslyn context used to register callbacks or emit generated source.</param>
    public void Initialize(GeneratorInitializationContext context)
    {
        context.RegisterForSyntaxNotifications(() => new AttributeSyntaxReceiver(Attributes));
    }

    /// <summary>
    /// Generates registration source for the attributed step definitions in the compilation.
    /// </summary>
    /// <param name="context">The Roslyn context used to register callbacks or emit generated source.</param>
    public abstract void Execute(GeneratorExecutionContext context);
    
    /// <summary>
    /// Emits a Unity initialization class that registers concrete classes carrying the selected attribute.
    /// </summary>
    /// <param name="context">The Roslyn context used to register callbacks or emit generated source.</param>
    /// <param name="attribute">The configured attribute name for which registration code is generated.</param>
    /// <param name="register">The callback that appends registration code for a fully qualified class name and its attribute data.</param>
    /// <param name="customMethods">An optional callback that appends helper methods to the generated registration class.</param>
    protected void GenerateForAttribute(
            GeneratorExecutionContext context, 
            string attribute, 
            Action<StringBuilder, string, AttributeData> register,
            Action<StringBuilder> customMethods = null)
        {
            if (context.SyntaxReceiver is not AttributeSyntaxReceiver receiver) return;
            
             var typesToRegister = new Dictionary<string, AttributeData>();

            foreach (var classDecl in receiver.CandidateClasses[attribute])
            {
                var semanticModel = context.Compilation.GetSemanticModel(classDecl.SyntaxTree);
                if (semanticModel.GetDeclaredSymbol(classDecl) is not INamedTypeSymbol classSymbol) continue;
                if (classSymbol.IsAbstract || classSymbol.TypeKind == TypeKind.Interface) continue;

                var attrData = classSymbol.GetAttributes().FirstOrDefault(ad =>
                    ad.AttributeClass?.Name == attribute + "Attribute" ||
                    ad.AttributeClass?.Name == attribute);

                if (attrData != null)
                {
                    typesToRegister.Add(classSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), attrData);
                }
            }

            if (typesToRegister.Count == 0) return;

            var assemblyName = context.Compilation.AssemblyName?.Replace(".", "_").Replace("-", "_");
            var generatedClassName = $"{attribute}Registration_{assemblyName}";

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine("using System.Reflection;");
            sb.AppendLine();
            sb.AppendLine($"internal static class {generatedClassName}");
            sb.AppendLine("{");
            sb.AppendLine("#if UNITY_EDITOR");
            sb.AppendLine("    [UnityEditor.InitializeOnLoadMethod]");
            sb.AppendLine("#endif");            
            sb.AppendLine("    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterAssembliesLoaded)]");
            sb.AppendLine("    private static void Register()");
            sb.AppendLine("    {");

            foreach (var type in typesToRegister) register(sb, type.Key, type.Value);

            sb.AppendLine("    }");
            customMethods?.Invoke(sb);
            sb.AppendLine("}");

            context.AddSource($"{generatedClassName}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }
    
}