namespace Damdor.Sequentio
{
    /// <summary>
    /// Specifies the direction in which sequence time advances.
    /// </summary>
    public enum PlayDirection
    {
        /// <summary>
        /// Advances from the beginning toward the end.
        /// </summary>
        Forward,
        
        /// <summary>
        /// Advances from the end toward the beginning.
        /// </summary>
        Reverse
    }
}